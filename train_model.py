"""
Train the crash-confirmation decision tree (PC) and export it for the ESP32.

    python train_model.py                      # synthetic data only
    python train_model.py --logs ride_logs/    # + your real labelled logs

Real log files must be named  log_<label>_<n>.csv  (main.py does this).
Labels counted as CRASH: fall, tipover, crash.  Anything else = not a crash
(normal, brake, pothole, laydown, transport, ...).

Output: ml_classifier.py  -> copy to the ESP32 next to main.py.
"""
import argparse
import csv
import glob
import os
import random
import time

import numpy as np
from sklearn.tree import DecisionTreeClassifier, export_text

from crash_algo import CrashDetector, Config, FEATURES
import sim_data

CRASH_LABELS = ("fall", "tipover", "crash")


# ---------------------------------------------------------------- real logs
def load_logs(folder):
    X, y, names, warnings = [], [], [], []
    for path in sorted(glob.glob(os.path.join(folder, "log_*.csv"))):
        label = os.path.basename(path)[4:].split("_")[0]
        rows = []
        with open(path) as f:
            for r in csv.DictReader(f):
                rows.append([float(r[k]) for k in ("t_ms", "ax", "ay", "az", "gx", "gy", "gz")])
        if len(rows) < 100:
            continue
        det = CrashDetector(Config)
        det.calibrate([tuple(r[1:7]) for r in rows if r[0] < rows[0][0] + 2000])
        prev = rows[0][0]
        got = None
        for r in rows:
            ev = det.update(*r[1:7], (r[0] - prev) / 1000.0)
            prev = r[0]
            if ev == "CRASH_SUSPECTED":
                got = det.gate_features
                break
        is_crash = label in CRASH_LABELS
        if got:
            X.append(got)
            y.append(1 if is_crash else 0)
            names.append("real:" + label)
        elif is_crash:
            warnings.append("%s labelled '%s' but the RULE GATE never fired - "
                            "lower ROLL_THRESHOLD_DEG / IMPACT_G" % (os.path.basename(path), label))
    return X, y, names, warnings


# ---------------------------------------------------------------- export
def export_tree(clf, n_train):
    t = clf.tree_
    lines = []

    def rec(node, ind):
        pad = "    " * ind
        if t.children_left[node] == -1:
            v = t.value[node][0]
            lines.append(pad + "return %s" % (v[1] > v[0]))
        else:
            fi, th = t.feature[node], t.threshold[node]
            lines.append(pad + "if f[%d] <= %.6f:  # %s" % (fi, th, FEATURES[fi]))
            rec(t.children_left[node], ind + 1)
            lines.append(pad + "else:")
            rec(t.children_right[node], ind + 1)
    rec(0, 1)
    head = '''# AUTO-GENERATED by train_model.py - do not edit by hand.
# Decision tree: confirms a crash after the rule gate fires.
# Trained on %d windows, %s.
# Feature order (must match crash_algo.FEATURES):
FEATURES = %r


def predict(f):
    """f = list of features in FEATURES order. True = crash, False = not a crash."""
''' % (n_train, time.strftime("%Y-%m-%d"), tuple(FEATURES))
    return head + "\n".join(lines) + "\n"


def load_generated(code):
    ns = {}
    exec(code, ns)
    return ns["predict"]


# ---------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--logs", help="folder with real log_<label>_<n>.csv files")
    ap.add_argument("--n", type=int, default=150, help="synthetic scenarios per type")
    ap.add_argument("--depth", type=int, default=4)
    ap.add_argument("--crash-weight", type=float, default=8.0,
                    help="penalty for missing a crash vs a false alarm")
    ap.add_argument("--out", default="ml_classifier.py")
    a = ap.parse_args()

    print("Generating synthetic training data (runs the real detector)...")
    X, y, kinds = sim_data.build_dataset(n=a.n, seed=1, verbose=True)
    w = [1.0] * len(X)
    if a.logs:
        Xr, yr, kr, warns = load_logs(a.logs)
        print("Real logs: %d gate-firing windows (%d crash)" % (len(Xr), sum(yr)))
        for m in warns:
            print("  WARNING:", m)
        X += Xr; y += yr; kinds += kr; w += [5.0] * len(Xr)      # real data counts 5x

    clf = DecisionTreeClassifier(max_depth=a.depth, min_samples_leaf=10,
                                 class_weight={0: 1.0, 1: a.crash_weight}, random_state=0)
    clf.fit(np.array(X), np.array(y), sample_weight=np.array(w))

    # ---- held-out test set (different random seed) ----
    Xt, yt, kt = sim_data.build_dataset(n=100, seed=999)
    Xt, yt = np.array(Xt), np.array(yt)
    pred = clf.predict(Xt)
    tp = ((pred == 1) & (yt == 1)).sum(); fn = ((pred == 0) & (yt == 1)).sum()
    fp = ((pred == 1) & (yt == 0)).sum(); tn = ((pred == 0) & (yt == 0)).sum()
    print("\nHeld-out test (windows where the rule gate fired):")
    print("  crash recall      %.1f%%  (%d/%d)  <- must stay ~100%%" % (100 * tp / (tp + fn), tp, tp + fn))
    print("  false-alarm rate  %.1f%%  (%d/%d)" % (100 * fp / (fp + tn), fp, fp + tn))
    for k in dict.fromkeys(kt):
        idx = [i for i, kk in enumerate(kt) if kk == k]
        corr = sum(pred[i] == yt[i] for i in idx)
        print("    %-14s %3d/%3d correct" % (k, corr, len(idx)))
    print("\nFeature importance:")
    for n_, imp in sorted(zip(FEATURES, clf.feature_importances_), key=lambda z: -z[1]):
        if imp > 0:
            print("    %-14s %.2f" % (n_, imp))
    print("\nTree:\n" + export_text(clf, feature_names=list(FEATURES)))

    # ---- export + verify generated code == sklearn ----
    code = export_tree(clf, len(X))
    predict = load_generated(code)
    mism = sum(bool(predict(list(map(float, r)))) != bool(p) for r, p in zip(Xt, pred))
    print("Exported code vs sklearn mismatches on test set: %d / %d" % (mism, len(Xt)))
    with open(a.out, "w") as f:
        f.write(code)
    print("Wrote", a.out)

    # ---- end-to-end: full detector, every scenario type ----
    r0 = sim_data.evaluate_end_to_end(None, n=40, seed=123)
    sim_data.print_end_to_end(r0, "END-TO-END  rule-based only (no ML):")
    r1 = sim_data.evaluate_end_to_end(predict, n=40, seed=123)
    sim_data.print_end_to_end(r1, "END-TO-END  hybrid (rule gate + decision tree):")


if __name__ == "__main__":
    main()
